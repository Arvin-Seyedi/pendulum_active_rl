function stop = e11a_capture()
% Observational callback: no assignments to the authoritative caller workspace.
stop = false;
folder = getenv('E11A_OUTPUT');
if isfile(fullfile(folder,'native.mat'))
    error('E11A:Overwrite','Refusing to overwrite an existing native snapshot');
end
wanted = {'E1','U_d','U1_global','X1','force','torque','u1','u2', ...
    'WOB','TOB','WOBc','WOBf','TOBc','TOBf','d','fv','fw','Z_a','Z_b', ...
    'cnt1','cnt2','Al1','K_M','D_M','M1_global','K1_global','D1_global', ...
    'F_M_d','F_M_e','F1_global','IC','Vs','force_d','torque_d','WOB_d', ...
    'TOB_d','err','angle','UU1','t','dt','n','N1','Mat_data2','TopR', ...
    'BotR','Gravity','K','k','E','A','m','l','Ix','Iy','Iz','J','G', ...
    'g','rho','Do','Di','Raleigh_a','Raleigh_b','P_initial','P_tail','R1', ...
    'epsilon','sigma','Rb','lw','Kc','zeta','gam','miu','d0','threshold', ...
    'a1','a2','b1','b2','v','w','fri_coef','deg','RR'};
available = evalin('caller','who');
wanted = wanted(ismember(wanted,available));
args = strjoin(cellfun(@(s) ['''' s ''''],wanted,'UniformOutput',false),',');
filename = strrep(fullfile(folder,'native.mat'),'''','''''');
evalin('caller',sprintf('save(''%s'',%s,''-v7'');',filename,args));
meta = struct('observational_only',true,'variables',{wanted}, ...
    'core_seconds_including_save',toc(getappdata(0,'E11A_clock')), ...
    'capture_stack',dbstack('-completenames'));
fid=fopen(fullfile(folder,'capture.json'),'w');
fprintf(fid,'%s\n',jsonencode(meta));fclose(fid);
end
